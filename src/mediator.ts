import {planDiff, type State, type Plan} from './planner';
import {runAgentTool, type AgentCall} from './tools';
import {negotiate, type Negotiation} from './negotiate';

// Offline rule-based mediator. It turns a plain-English request into typed tool calls.
// It is NOT a language model. A live model could replace parseRequest later and would
// be limited to the same typed calls, with no approve tool.
export type Understanding = {person:string; quietId:string; newStart:number; newEnd:number; summary:string};
export type MediationResult =
 | {status:'needs_clarification'; question:string; engine:'offline-rules'}
 | {status:'proposal'; engine:'offline-rules'; understood:string; calls:AgentCall[]; toolTrace:{tool:string;note:string}[]; plans:Plan[]; negotiation:Record<string,Negotiation[]>; diffs:Record<string,ReturnType<typeof planDiff>>; applied:boolean; state:State};

function clock(text:string):number[]{
 const out:number[]=[];
 for(const m of text.matchAll(/\b(\d{1,2})(?::(\d{2}))?\s*(am|pm)?\b/gi)){
  let h=Number(m[1]);const min=m[2]?Number(m[2]):0;const ap=m[3]?.toLowerCase();
  if(!ap&&!m[2])continue; // a bare number is not a time
  if(ap==='pm'&&h<12)h+=12;if(ap==='am'&&h===12)h=0;
  if(h>23||min>59)continue;out.push(h*60+min)}
 return out;
}
function minutesShift(text:string):number|null{
 const m=text.match(/(\d+)\s*(min|mins|minutes|hour|hours|hr|hrs)\b/i)||(/\ban hour\b/i.test(text)?['', '1','hour']:null);
 if(!m)return null;const n=Number(m[1])*(/^h/i.test(m[2])?60:1);return /earlier|before|back/i.test(text)?-n:n;
}
export function parseRequest(s:State,text:string):Understanding|{question:string}{
 const lower=text.toLowerCase();
 const people=[...new Set(s.quiet.map(q=>q.person))].filter(p=>new RegExp('\\b'+p.toLowerCase().replace(/[.*+?^${}()|[\]\\]/g,'\\$&')+'\\b').test(lower));
 if(people.length!==1)return {question:people.length?`Which person do you mean: ${people.join(' or ')}?`:`Whose quiet window changed? Known people: ${[...new Set(s.quiet.map(q=>q.person))].join(', ')}.`};
 const mine=s.quiet.filter(q=>q.person===people[0]);
 let q=mine[0];
 if(mine.length>1){const byWord=mine.filter(x=>x.label.toLowerCase().split(/\s+/).some(w=>w.length>3&&lower.includes(w)));if(byWord.length!==1)return {question:`${people[0]} has ${mine.length} windows (${mine.map(x=>x.label).join(', ')}). Which one changed?`};q=byWord[0]}
 const dur=q.end-q.start,times=clock(text),shift=minutesShift(text);
 let ns:number,ne:number,how:string;
 if(times.length>=2){[ns,ne]=[times[0],times[1]];how=`now ${parseTimeLabel(ns)}-${parseTimeLabel(ne)}`}
 else if(times.length===1&&/\b(end|ends|until|till)\b/.test(lower)){ne=times[0];ns=ne-dur;how=`now ends ${parseTimeLabel(ne)}`}
 else if(times.length===1){ns=times[0];ne=ns+dur;how=`now starts ${parseTimeLabel(ns)}`}
 else if(shift!==null){ns=q.start+shift;ne=q.end+shift;how=`moved ${Math.abs(shift)} min ${shift>0?'later':'earlier'}`}
 else return {question:`What is ${people[0]}'s new time for "${q.label}"? For example "moved to 4pm" or "30 minutes later".`};
 if(ns<0||ne>1440||ns>=ne)return {question:'That time does not fit inside one day. Please give a start and end between 00:00 and 24:00.'};
 return {person:q.person,quietId:q.id,newStart:ns,newEnd:ne,summary:`${q.person}'s "${q.label}" ${how}.`};
}
const parseTimeLabel=(n:number)=>`${String(Math.floor(n/60)).padStart(2,'0')}:${String(n%60).padStart(2,'0')}`;

// apply=false: preview on a copy, nothing saved. apply=true: caller saves state after the user confirmed.
export function mediate(s:State,text:string,apply:boolean):MediationResult{
 if(typeof text!=='string'||!text.trim()||text.length>300)return {status:'needs_clarification',question:'Tell me what changed, in one short sentence.',engine:'offline-rules'};
 const u=parseRequest(s,text);
 if('question' in u)return {status:'needs_clarification',question:u.question,engine:'offline-rules'};
 const trace:{tool:string;note:string}[]=[];
 const calls:AgentCall[]=[{name:'get_household'},{name:'update_quiet_window',revision:s.revision,id:u.quietId,start:u.newStart,end:u.newEnd}];
 runAgentTool(s,calls[0]);trace.push({tool:'get_household',note:'Read declared quiet windows and chores.'});
 const next=runAgentTool(s,calls[1]).state;trace.push({tool:'update_quiet_window',note:u.summary+' Any saved approval is invalidated.'});
 const propose:AgentCall={name:'propose_plans',revision:next.revision};calls.push(propose);
 const plans=runAgentTool(next,propose).result as Plan[];trace.push({tool:'propose_plans',note:`${plans.length} options generated by the deterministic planner. Nothing approved.`});
 const negotiation:Record<string,Negotiation[]>={},diffs:Record<string,ReturnType<typeof planDiff>>={};
 for(const p of plans){negotiation[p.id]=negotiate(next,p);diffs[p.id]=planDiff(next,p)}
 return {status:'proposal',engine:'offline-rules',understood:u.summary,calls,toolTrace:trace,plans,negotiation,diffs,applied:apply,state:next};
}
